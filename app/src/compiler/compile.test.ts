describe('compile: safety rails', () => {
  it('REFUSES a loop-risky graph when guards are disabled', () => {
    const bp: Blueprint = {
      version: 1,
      meta: { name: 'Ouroboros' },
      nodes: [
        node('t', 'trigger.comment', { phrase: '' }),
        node('a', 'agent.claude', { promptRef: 'p.md' }),
        node('s', 'sink.comment', { instruction: 'replies' }),
      ],
      edges: [edge('e1', 't', 'a'), edge('e2', 'a', 's')],
    };
    const { workflows } = compile(bp, { unsafeNoGuards: true });
    expect(workflows[0].diagnostics.some((d) => d.level === 'error' && d.message.includes('REFUSED'))).toBe(true);
    expect(workflows[0].yaml).toBe('');
  });

  it('warns on triggerless components without emitting', () => {
    const bp: Blueprint = {
      version: 1,
      meta: { name: 'Idle' },
      nodes: [node('a', 'agent.claude', { promptRef: 'p.md' })],
      edges: [],
    };
    const { workflows, diagnostics } = compile(bp);
    expect(workflows).toHaveLength(0);
    expect(diagnostics.some((d) => d.message.includes('no trigger'))).toBe(true);
  });

  it('is deterministic: same blueprint → same hash and yaml', () => {
    const a = compile(triageLine).workflows[0].yaml;
    const b = compile(triageLine).workflows[0].yaml;
    expect(a).toBe(b);
  });
});
