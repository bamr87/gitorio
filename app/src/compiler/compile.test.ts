import { describe, expect, it } from 'vitest';
import { compile } from './compile';
import type { Blueprint } from '../blueprint/types';

const node = (id: string, type: string, config: Record<string, unknown> = {}) => ({
  id,
  type,
  position: { x: 0, y: 0 },
  config,
});
const edge = (id: string, from: string, to: string) => ({
  id,
  from: { node: from, port: 'out' },
  to: { node: to, port: 'in' },
});

const triageLine: Blueprint = {
  version: 1,
  meta: { name: 'Issue Triage Line', repo: 'o/r' },
  nodes: [
    node('t1', 'trigger.issue_opened'),
    node('a1', 'agent.claude', {
      promptRef: '.factory/prompts/triage.md',
      model: 'claude-sonnet-4-6',
      maxTurns: 8,
    }),
    node('s1', 'sink.label', { labels: '' }),
    node('s2', 'sink.comment', { instruction: 'summarizes the triage decision in 3 lines' }),
  ],
  edges: [edge('e1', 't1', 'a1'), edge('e2', 'a1', 's1'), edge('e3', 'a1', 's2')],
};

describe('compile: integrated agent line (trigger → agent → sinks)', () => {
  const { workflows, diagnostics } = compile(triageLine);
  const wf = workflows[0];

  it('emits one workflow with the factory-- filename convention', () => {
    expect(diagnostics.filter((d) => d.level === 'error')).toHaveLength(0);
    expect(workflows).toHaveLength(1);
    expect(wf.filename).toBe('factory--issue-triage-line.yml');
  });

  it('carries the generated header + blueprint hash', () => {
    expect(wf.yaml).toContain('GENERATED BY GITFACTORY');
    expect(wf.yaml).toMatch(/hash: [0-9a-f]{8}/);
  });

  it('maps the trigger to on.issues [opened]', () => {
    expect(wf.yaml).toContain('issues:');
    expect(wf.yaml).toContain('- opened');
  });

  it('uses claude-code-action@v1 with prompt + claude_args (v1 interface, not deprecated inputs)', () => {
    expect(wf.yaml).toContain('anthropics/claude-code-action@v1');
    expect(wf.yaml).toContain('--model claude-sonnet-4-6');
    expect(wf.yaml).toContain('--max-turns 8');
    expect(wf.yaml).not.toContain('direct_prompt');
    expect(wf.yaml).not.toContain('allowed_tools:');
  });

  it('defaults agent auth to Claude Code OAuth token with an ANTHROPIC_API_KEY fallback', () => {
    expect(wf.yaml).toContain('claude_code_oauth_token: ${{ secrets.CLAUDE_CODE_OAUTH_TOKEN }}');
    // API key is the fallback, passed only when the OAuth secret is unset
    expect(wf.yaml).toContain("secrets.CLAUDE_CODE_OAUTH_TOKEN == '' && secrets.ANTHROPIC_API_KEY");
  });

  it('references the repo prompt file instead of inlining it', () => {
    expect(wf.yaml).toContain('.factory/prompts/triage.md');
  });

  it('turns downstream sinks into numbered obligations + scoped tool grants', () => {
    expect(wf.yaml).toContain('OBLIGATIONS');
    expect(wf.yaml).toContain('[sink.label s1]');
    expect(wf.yaml).toContain('[sink.comment s2]');
    expect(wf.yaml).toContain('Bash(gh issue edit:*)');
    expect(wf.yaml).toContain('Bash(gh issue comment:*)');
    expect(wf.yaml).not.toContain('Bash(gh pr comment:*)'); // no PR trigger on this line
  });

  it('computes least-privilege permissions and per-entity concurrency', () => {
    expect(wf.yaml).toContain('issues: write');
    expect(wf.yaml).toContain('id-token: write');
    expect(wf.yaml).not.toContain('pull-requests: write');
    expect(wf.yaml).toContain('concurrency:');
    expect(wf.yaml).toContain('factory--issue-triage-line-${{ github.event.issue.number');
  });

  it('injects the bot loop-guard on the event actor (sender), not the author', () => {
    expect(wf.yaml).toContain("github.event.sender.type != 'Bot'");
    expect(wf.yaml).not.toContain('github.event.issue.user.type');
  });
});

describe('compile: loop-guard identity (regression, golden rule #6)', () => {
  // Bug: the guard checked github.event.issue.user.type (the issue AUTHOR). On an
  // issues.labeled event the actor is the LABELLER (github.event.sender), so a bot
  // applying a label to a human-authored issue passed the guard and the line
  // (issue_labeled → agent → sink.label) could retrigger itself forever.
  const labeledLine: Blueprint = {
    version: 1,
    meta: { name: 'Relabeler' },
    nodes: [
      node('t', 'trigger.issue_labeled', { label: 'needs-triage' }),
      node('a', 'agent.claude', { promptRef: 'p.md' }),
      node('s', 'sink.label', { labels: 'triaged' }),
    ],
    edges: [edge('e1', 't', 'a'), edge('e2', 'a', 's')],
  };

  it('guards issue_labeled on the actor (sender), never the issue author', () => {
    const wf = compile(labeledLine).workflows[0];
    expect(wf.yaml).toContain("github.event.sender.type != 'Bot'");
    // the whole point of the fix — the author check must be gone
    expect(wf.yaml).not.toContain('github.event.issue.user.type');
  });

  it('keeps the label-name guard alongside the actor guard', () => {
    const wf = compile(labeledLine).workflows[0];
    expect(wf.yaml).toContain('- labeled');
    expect(wf.yaml).toContain("github.event.label.name == 'needs-triage'");
  });

  it('guards pull_request (incl. synchronize) on the actor, not the PR author', () => {
    // A bot pushing to the PR branch fires synchronize; the pusher is the actor, so
    // pull_request.user (the author) would let the agent-authored push retrigger.
    const prLine: Blueprint = {
      version: 1,
      meta: { name: 'PR Reviewer' },
      nodes: [
        node('t', 'trigger.pr_opened', { alsoOnSync: 'yes' }),
        node('a', 'agent.claude', { promptRef: 'p.md' }),
        node('s', 'sink.comment', { instruction: 'reviews the diff' }),
      ],
      edges: [edge('e1', 't', 'a'), edge('e2', 'a', 's')],
    };
    const wf = compile(prLine).workflows[0];
    expect(wf.yaml).toContain('- synchronize');
    expect(wf.yaml).toContain("github.event.sender.type != 'Bot'");
    expect(wf.yaml).not.toContain('github.event.pull_request.user.type');
  });
});

