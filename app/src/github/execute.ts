// Deploy orchestration: the I/O side that pairs with the pure planner in deploy.ts.
// gatherRepoState fetches what the planner needs; executePlan writes the plan to the
// repo as a single commit on the default branch, or on a fresh branch behind a PR.

import type { BlueprintMeta } from '../blueprint/types';
import { kebab } from '../blueprint/types';
import { BLUEPRINT_PATH, WORKFLOW_DIR, type RepoState } from './deploy';
import type { DeployMode, DeployPlan, GithubClient, RepoFile, RepoRef } from './types';

const FACTORY_WF = /^factory--.*\.ya?ml$/;

/** Fetch the current blueprint, factory workflow files (with content), and prompt paths. */
export async function gatherRepoState(client: GithubClient, repo: RepoRef): Promise<RepoState> {
  const [blueprintFile, wfEntries, promptEntries] = await Promise.all([
    client.getFile(repo, BLUEPRINT_PATH),
    client.listDir(repo, WORKFLOW_DIR),
    client.listDir(repo, '.factory/prompts'),
  ]);

  const factoryEntries = wfEntries.filter((e) => e.type === 'file' && FACTORY_WF.test(e.name));
  const fetched = await Promise.all(factoryEntries.map((e) => client.getFile(repo, e.path)));
  const workflowFiles = fetched.filter((f): f is RepoFile => f !== null);
  const promptPaths = promptEntries.filter((e) => e.type === 'file').map((e) => e.path);

  return { blueprintFile, workflowFiles, promptPaths };
}

export interface DeployOutcome {
  mode: DeployMode;
  changes: number;
  /** PR url when mode === 'pr'. */
  prUrl?: string;
  branch?: string;
}

/** Apply a plan. Writes/deletes run sequentially to avoid sha races and rate spikes. */
export async function executePlan(
  client: GithubClient,
  repo: RepoRef,
  plan: DeployPlan,
  opts: { mode: DeployMode; meta: BlueprintMeta },
): Promise<DeployOutcome> {
  const changes = plan.writes.length + plan.deletes.length;
  const message = `factory: deploy ${opts.meta.name || 'blueprint'}`;

  if (opts.mode === 'pr') {
    const base = await client.getDefaultBranch(repo);
    const branch = `gitfactory/deploy-${kebab(opts.meta.name)}-${Date.now().toString(36)}`;
    await client.createBranch(repo, branch, base);
    for (const w of plan.writes) {
      await client.putFile(repo, w.path, w.content, message, { sha: w.sha, branch });
    }
    for (const d of plan.deletes) {
      await client.deleteFile(repo, d.path, d.sha, message, { branch });
    }
    const prUrl = await client.createPullRequest(repo, {
      title: message,
      head: branch,
      base,
      body: 'Generated by GitFactory — blueprint + compiled workflows.\n\nEdit the blueprint, not the generated YAML.',
    });
    return { mode: 'pr', changes, prUrl, branch };
  }

  for (const w of plan.writes) {
    await client.putFile(repo, w.path, w.content, message, { sha: w.sha });
  }
  for (const d of plan.deletes) {
    await client.deleteFile(repo, d.path, d.sha, message);
  }
  return { mode: 'commit', changes };
}
