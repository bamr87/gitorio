import { readFileSync } from 'node:fs';
import { describe, expect, it } from 'vitest';
import { MACHINES } from './registry';
import {
  MACHINE_REFERENCE_COMMAND,
  MACHINE_REFERENCE_PATH,
  renderMachineReference,
} from './reference';

// Freshness guard for the generated machine reference (UPS-DOC-05): the committed
// docs/reference/machines.md must be exactly what the registry renders, so a machine added or
// changed without regenerating fails `npm test` (and therefore CI) rather than drifting.
describe('generated machine reference ↔ registry', () => {
  const rendered = renderMachineReference(MACHINES);

  it(`${MACHINE_REFERENCE_PATH} is fresh — regenerate with \`${MACHINE_REFERENCE_COMMAND}\``, () => {
    const committed = readFileSync(
      new URL(`../../../${MACHINE_REFERENCE_PATH}`, import.meta.url),
      'utf8',
    );
    expect(committed).toBe(rendered);
  });

  it('opens with the GENERATED header naming the rebuild command', () => {
    expect(rendered.split('\n')[0]).toBe(
      `<!-- GENERATED by \`${MACHINE_REFERENCE_COMMAND}\` from app/src/machines/registry.ts — do not edit by hand -->`,
    );
  });

  it('gives every registry machine exactly one section', () => {
    for (const m of MACHINES) {
      const headings = rendered.split('\n').filter((line) => line === `### \`${m.type}\``);
      expect(headings, m.type).toHaveLength(1);
    }
  });

  it('is deterministic', () => {
    expect(renderMachineReference(MACHINES)).toBe(rendered);
  });
});
